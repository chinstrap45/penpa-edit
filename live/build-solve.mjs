const occurrences = (text, part) => text.split(part).length - 1

// `indexHtml` is the text of `docs/index.html`; returns the text of `docs/solve.html`.
export function buildSolve (indexHtml) {
  const eol = indexHtml.includes('\r\n') ? '\r\n' : '\n'
  const own = (text) => text.replaceAll('\n', eol)
  let html = indexHtml
  for (const { name, find, replace } of EDITS) {
    const count = occurrences(html, own(find))
    if (count !== 1) {
      throw new Error(`build-solve: the text for the edit "${name}" occurs ${count} times in index.html, not once: port upstream's change into EDITS in live/build-solve.mjs`)
    }
    html = html.replace(own(find), () => own(replace))
  }
  return html.endsWith('\n') ? html : html + eol
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('solve.html', DOCS), buildSolve(await readFile(new URL('index.html', DOCS), 'utf8')))
}
